@dataclass
class YaraMatch:
    """Represents a Yara rule match."""
    rule: str
    namespace: str
    tags: List[str]
    meta: Dict[str, Any]
    strings: List[Tuple[int, bytes, str]]  # (offset, data, identifier)
    file_path: Optional[str] = None
    severity: str = "medium"
    description: str = ""


@dataclass
class YaraRuleSet:
    """Represents a compiled set of Yara rules."""
    name: str
    compiled_rules: Any
    source_path: Path
    rule_count: int
    last_compiled: datetime
    error: Optional[str] = None


