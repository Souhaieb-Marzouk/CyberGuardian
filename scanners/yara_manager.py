    def __init__(self, rules_dir: Optional[Path] = None):
        # Rules live in the user data directory: the application directory is
        # read-only for frozen (PyInstaller) builds.
        self.rules_dir = Path(rules_dir) if rules_dir else (Path(USER_DATA_DIR) / "yara_rules")
        self.bundled_rules_dir = Path(YARA_RULES_DIR)
        self.compiled_rulesets: Dict[str, YaraRuleSet] = {}
        self._lock = threading.RLock()
        self._loaded = False
        self._compile_cache: Dict[str, Tuple[float, int, YaraRuleSet]] = {}

        # Ensure the writable rules directory exists. Failure is not fatal:
        # bundled rules may still be available.
        try:
            self.rules_dir.mkdir(parents=True, exist_ok=True)
        except OSError as e:
            logger.warning(
                f"Could not create YARA rules directory {self.rules_dir}: {e}. "
                f"Using bundled rules only."
            )

        # Rule file patterns
        self.rule_extensions = {'.yar', '.yara'}
    
    def load_rules(self, force_reload: bool = False) -> bool:
        """
        Load and compile all Yara rules from the rules directory.
        
        Args:
            force_reload: If True, reload even if already loaded
        
        Returns:
            True if successful, False otherwise
        """
        with self._lock:
            if self._loaded and not force_reload:
                return True

            if not YARA_AVAILABLE:
                logger.error(
                    "yara-python is not installed - YARA detection is disabled. "
                    "Install it with: pip install yara-python"
                )
                return False

            if force_reload:
                self._compile_cache.clear()

            logger.info(f"Loading Yara rules from {self.rules_dir}")
            
            # Clear existing rules
            self.compiled_rulesets.clear()

            # Repair default rule files generated by older versions (two of them
            # did not compile: a missing math import and unused strings).
            self._upgrade_default_rules()

            # Find all rule files
            rule_files = self._find_rule_files()
            
            if not rule_files:
                logger.warning("No Yara rule files found")
                self._create_default_rules()
                rule_files = self._find_rule_files()
            
            # Compile rules by category
            total_rules = 0
            errors = []
            
            for rule_file in rule_files:
                try:
                    ruleset = self._compile_rule_file(rule_file)
                    if ruleset:
                        self.compiled_rulesets[ruleset.name] = ruleset
                        total_rules += ruleset.rule_count
                except Exception as e:
                    error_msg = f"Failed to compile {rule_file}: {e}"
                    logger.error(error_msg)
                    errors.append(error_msg)
            
            self._loaded = True
            
            logger.info(
                f"Loaded {total_rules} Yara rules from "
                f"{len(self.compiled_rulesets)} rulesets"
            )
            
            return len(errors) == 0
    
    def _find_rule_files(self) -> List[Path]:
        """Find YARA rule files in the writable and bundled directories."""
        rule_files: List[Path] = []
        seen_names = set()

        for directory in (self.rules_dir, self.bundled_rules_dir):
            try:
                if not directory or not Path(directory).is_dir():
                    continue
                for root, _, files in os.walk(directory):
                    for name in sorted(files):
                        if Path(name).suffix.lower() not in self.rule_extensions:
                            continue
                        if name in seen_names:
                            continue
                        seen_names.add(name)
                        rule_files.append(Path(root) / name)
            except OSError as e:
                logger.warning(f"Could not enumerate YARA rules in {directory}: {e}")

        return sorted(rule_files)

    def _compile_rule_file(self, filepath: Path) -> Optional[YaraRuleSet]:
        """Compile a single Yara rule file (cached by mtime/size)."""
        try:
            stat = filepath.stat()
        except OSError as e:
            logger.error(f"Cannot stat Yara rule file {filepath}: {e}")
            return None

        cache_key = str(filepath)
        cached = self._compile_cache.get(cache_key)
        if cached and cached[0] == stat.st_mtime and cached[1] == stat.st_size:
            return cached[2]

        content = ""
        try:
            with open(filepath, 'r', encoding='utf-8', errors='ignore') as f:
                content = f.read()

            rule_count = len(re.findall(r'^\s*rule\s+\w+\s*[{:]', content, re.MULTILINE))
            if rule_count == 0:
                logger.debug(f"No rules found in {filepath}")
                return None

            # filepath= enables relative includes and better error messages
            compiled = yara.compile(filepath=str(filepath))

            try:
                relative_path = filepath.relative_to(self.rules_dir)
            except ValueError:
                relative_path = filepath.relative_to(self.bundled_rules_dir) \
                    if filepath.is_relative_to(self.bundled_rules_dir) else Path(filepath.name)

            category = relative_path.parts[0] if len(relative_path.parts) > 1 else 'general'

            ruleset = YaraRuleSet(
                name=f"{category}_{filepath.stem}",
                compiled_rules=compiled,
                source_path=filepath,
                rule_count=rule_count,
                last_compiled=datetime.utcnow(),
            )

            self._compile_cache[cache_key] = (stat.st_mtime, stat.st_size, ruleset)
            return ruleset

        except yara.SyntaxError as e:
            logger.error(f"Yara syntax error in {filepath}: {e}")
            return None
        except yara.Error as e:
            logger.error(f"Yara error in {filepath}: {e}")
            return None

    def _upgrade_default_rules(self) -> None:
        """Fix known-broken default rules written by earlier releases."""
        try:
            packed = self.rules_dir / 'packed_executable.yar'
            if packed.exists():
                text = packed.read_text(encoding='utf-8')
                if 'math.entropy' in text and 'import "math"' not in text:
                    packed.write_text('import "math"\n\n' + text, encoding='utf-8')
                    logger.info("Repaired packed_executable.yar (missing math import)")

            apis = self.rules_dir / 'suspicious_apis.yar'
            if apis.exists():
                text = apis.read_text(encoding='utf-8')
                if '$api8' in text:
                    condition = text.split('condition:', 1)[-1]
                    unused = [name for name in ('$api8', '$api9', '$api10')
                              if name not in condition]
                    if unused:
                        kept = [
                            line for line in text.splitlines()
                            if not any(line.strip().startswith(name) for name in unused)
                        ]
                        apis.write_text('\n'.join(kept) + '\n', encoding='utf-8')
                        logger.info("Repaired suspicious_apis.yar (unreferenced strings)")
        except OSError as exc:
            logger.warning(f"Could not upgrade default Yara rules: {exc}")

